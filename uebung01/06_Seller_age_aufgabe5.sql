
SELECT
    CASE
        WHEN GROUPING(
            EXTRACT(YEAR FROM SYSDATE) -
            EXTRACT(YEAR FROM seller.DATE_OF_BIRTH)
        ) = 1 THEN 'alle'
        ELSE TO_CHAR(
            EXTRACT(YEAR FROM SYSDATE) -
            EXTRACT(YEAR FROM seller.DATE_OF_BIRTH)
        )
    END AS AGE_OF_SELLER,

    CASE
        WHEN GROUPING(t.YEAR) = 1 THEN 'alle'
        ELSE TO_CHAR(t.YEAR)
    END AS SALE_YEAR,

    CASE
        WHEN GROUPING(p.PRODUCT_CATEGORY) = 1 THEN 'alle'
        ELSE p.PRODUCT_CATEGORY
    END AS PRODUCT_CATEGORY,

    NVL(SUM(s.TURNOVER), 0) AS TOTAL_TURNOVER

FROM Sale s

JOIN Time t
    ON t.TIME_ID = s.TIME_ID

JOIN Product p
    ON p.PRODUCT_ID = s.PRODUCT_ID

JOIN Seller seller
    ON seller.SELLER_ID = s.SELLER_ID

GROUP BY CUBE (
    EXTRACT(YEAR FROM SYSDATE) -
    EXTRACT(YEAR FROM seller.DATE_OF_BIRTH),
    t.YEAR,
    p.PRODUCT_CATEGORY
)

ORDER BY
    GROUPING(
        EXTRACT(YEAR FROM SYSDATE) -
        EXTRACT(YEAR FROM seller.DATE_OF_BIRTH)
    ) ASC,
    EXTRACT(YEAR FROM SYSDATE) -
    EXTRACT(YEAR FROM seller.DATE_OF_BIRTH) ASC NULLS LAST,
    GROUPING(t.YEAR) ASC,
    t.YEAR DESC NULLS LAST,
    GROUPING(p.PRODUCT_CATEGORY) ASC,
    p.PRODUCT_CATEGORY ASC NULLS LAST;
