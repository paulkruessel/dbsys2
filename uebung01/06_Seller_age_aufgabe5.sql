SELECT
    EXTRACT(YEAR FROM SYSDATE) - EXTRACT(YEAR FROM seller.DATE_OF_BIRTH) AS AGE_OF_SELLER,
    t.Year,
    p.Product_Category,
    SUM(s.TURNOVER) AS TOTAL_TURNOVER
FROM Sale s
JOIN Time t
    ON t.TIME_ID = s.TIME_ID
JOIN PRODUCT p
    ON p.PRODUCT_ID = s.PRODUCT_ID
JOIN SELLER seller
    ON seller.SELLER_ID = s.SELLER_ID
    
GROUP BY CUBE (AGE_OF_SELLER, t.YEAR, p.PRODUCT_CATEGORY)
ORDER BY AGE_OF_SELLER ASC, t.YEAR DESC, p.PRODUCT_CATEGORY ASC, TOTAL_TURNOVER DESC;